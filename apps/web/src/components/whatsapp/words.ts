export type WhatsAppWords = typeof en;

/** The screens' words in the person's language: Portuguese for `pt-*`, English for every other. */
export function useWords(): WhatsAppWords {
  const { i18n } = useTranslation();
  return i18n.language?.toLowerCase().startsWith("pt") ? ptBR : en;
}

/** A phone's digits as people read them: Brazil's shape for `55…`, a plain `+` for the rest. */
export function showPhone(digits: string | null): string {
  if (!digits) return "";
  const br = /^55(\d{2})(\d{4,5})(\d{4})$/.exec(digits);
  return br ? `+55 ${br[1]} ${br[2]}-${br[3]}` : `+${digits}`;
}
